// What both map pipelines (tools/map/hex, tools/map/area) produce from their sources, so that the rules and the client
// don't depend on the kind of map:
//
// - src/rules/game/map-data.ts: the spaces, their names, adjacency and terrain, for the rules;
// - src/play/map.svg: the map image, a clickable element per space (id = space id, data-anchor = where pieces go),
//   the terrain overlay (hidden until the menu shows it) and the pieces layer;
// - tools/map/map.json: the borders and where they are, for the terrain editor;
// - the map's size in src/play/play.html.
import {existsSync, readFileSync, writeFileSync} from "node:fs"
import type {Point} from "@rzymek/rally-the-troops-module/map"
import {readTerrain, type Terrain} from "@rzymek/rally-the-troops-module/tools"
import {LAYERS} from "./layers.ts"

export interface MapSpace {
  id: string
  /** How the log and prompts name it. */
  name: string
  anchor: Point
  /** The SVG markup of its outline, without an id, e.g. `<polygon points="..."/>`. */
  shape: string
}

export interface MapBorder {
  a: string
  b: string
  /** Its middle, where the editor shows it. */
  at: Point
  /** The border as drawn, if known (areas); otherwise a line across the line between the anchors (hexsides). */
  segments?: [Point, Point][]
}

export interface MapSource {
  kind: "hex" | "area"
  width: number
  height: number
  /** The printed map, in public/; without it a plain background stands in. */
  image?: string
  /** Shared SVG definitions, e.g. the hex outline. */
  defs?: string
  spaces: MapSpace[]
  borders: MapBorder[]
}

export const borderKey = (a: string, b: string) => a < b ? `${a}|${b}` : `${b}|${a}`

const root = new URL("../../", import.meta.url)
const file = (path: string) => new URL(path, root)
export const terrainFile = (kind: MapSource["kind"]) => file(`tools/map/${kind}/terrain.json`).pathname

/** The terrain of the map, checked against its spaces and borders. */
export function checkTerrain(source: MapSource, terrain: Terrain): string[] {
  const spaces = new Set(source.spaces.map(it => it.id))
  const borders = new Set(source.borders.map(it => borderKey(it.a, it.b)))
  const problems: string[] = []
  for (const [name, layer] of Object.entries(LAYERS)) {
    for (const key of terrain[name] ?? []) {
      if (layer.kind === "space" && !spaces.has(key)) problems.push(`${name}: no space ${key}`)
      if (layer.kind === "border" && !borders.has(key)) problems.push(`${name}: no border ${key}`)
    }
  }
  return problems
}

const n = (value: number) => String(Math.round(value * 100) / 100)
const pathOf = (points: [Point, Point][]) => points.map(([[ax, ay], [bx, by]]) => `M${n(ax)} ${n(ay)}L${n(bx)} ${n(by)}`).join("")

/** A border as a line across the line between the anchors of its spaces, at its middle. */
function borderLine(border: MapBorder, anchors: Map<string, Point>): [Point, Point][] {
  if (border.segments) return border.segments
  const [ax, ay] = anchors.get(border.a)!, [bx, by] = anchors.get(border.b)!
  const d = Math.hypot(bx - ax, by - ay) || 1
  const half = Math.min(d * 0.29, 60)
  const ux = -(by - ay) / d * half, uy = (bx - ax) / d * half
  const [x, y] = border.at
  return [[[x - ux, y - uy], [x + ux, y + uy]]]
}

export function renderMap(source: MapSource, terrain: Terrain): {mapData: string, mapSvg: string, mapJson: string} {
  const problems = checkTerrain(source, terrain)
  if (problems.length > 0) throw new Error(`terrain.json doesn't match the map:\n  ${problems.join("\n  ")}`)
  const {kind, width, height, spaces, borders} = source
  const anchors = new Map(spaces.map(it => [it.id, it.anchor]))

  const adjacent: Record<string, string[]> = Object.fromEntries(spaces.map(it => [it.id, []]))
  for (const {a, b} of borders) {
    adjacent[a].push(b)
    adjacent[b].push(a)
  }
  for (const list of Object.values(adjacent)) list.sort()

  const layerLines = Object.keys(LAYERS).map(name => `  ${name}: ${JSON.stringify([...(terrain[name] ?? [])].sort())},`)
  const mapData = `// Generated by tools/map/${kind}/gen-map.ts: don't edit, run \`pnpm gen:map${kind === "area" ? ":area" : ""}\`.
// Terrain comes from tools/map/${kind}/terrain.json, marked with \`pnpm edit:terrain\`.

/** Every space of the map: its id, as the log, actions and the client know it. */
export const SPACES: readonly string[] = ${JSON.stringify(spaces.map(it => it.id))}

/** How the log and prompts name each space. */
export const NAMES: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(spaces.map(it => [it.id, it.name])))}

/** The spaces next to each space, sorted. */
export const ADJACENT: Readonly<Record<string, readonly string[]>> = {
${Object.entries(adjacent).map(([id, list]) => `  ${JSON.stringify(id)}: ${JSON.stringify(list)},`).join("\n")}
}

/** The spaces, or borders ("<id>|<id>", sorted), of each terrain layer of tools/map/layers.ts. */
export const TERRAIN = {
${layerLines.join("\n")}
} as const
`

  const overlay = Object.entries(LAYERS).map(([name, layer]) => {
    const keys = new Set(terrain[name] ?? [])
    if (layer.kind === "space") {
      const shapes = spaces.filter(it => keys.has(it.id)).map(({anchor: [x, y], shape}) =>
        `      <g transform="translate(${n(x)} ${n(y)}) scale(${layer.scale ?? 1}) translate(${n(-x)} ${n(-y)})">${shape}</g>`)
      return `    <g class="terrain-${name}" fill="${layer.color}" fill-opacity="0.5" stroke="none"><title>${layer.label}</title>\n${shapes.join("\n")}\n    </g>`
    }
    const lines = borders.filter(it => keys.has(borderKey(it.a, it.b))).map(it => pathOf(borderLine(it, anchors)))
    return `    <path class="terrain-${name}" d="${lines.join("")}" stroke="${layer.color}" stroke-width="8" stroke-linecap="round" fill="none"><title>${layer.label}</title></path>`
  })

  const mapSvg = `<svg id="map" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}">
  ${source.defs ? `<defs>${source.defs}</defs>\n  ` : ""}${source.image
    ? `<image id="mapbg" href="${source.image}" width="${width}" height="${height}"/>`
    : `<rect id="mapbg" width="${width}" height="${height}"/>`}
  <g id="spaces">
${spaces.map(it => "    " + it.shape.replace(/^<(\w+)/, `<$1 id="${it.id}" data-anchor="${n(it.anchor[0])},${n(it.anchor[1])}"`)).join("\n")}
  </g>
  <g id="terrain-overlay">
${overlay.join("\n")}
  </g>
  <g id="pieces"></g>
</svg>
`

  const mapJson = JSON.stringify({kind, borders: borders.map(({a, b, at}) => ({key: borderKey(a, b), a, b, at}))}) + "\n"
  return {mapData, mapSvg, mapJson}
}

/** Writes what renderMap makes, and the map's size into play.html. */
export function writeMap(source: MapSource) {
  const terrain = readTerrain(terrainFile(source.kind), LAYERS)
  const {mapData, mapSvg, mapJson} = renderMap(source, terrain)
  writeFileSync(file("src/rules/game/map-data.ts"), mapData)
  writeFileSync(file("src/play/map.svg"), mapSvg)
  writeFileSync(file("tools/map/map.json"), mapJson)
  const html = file("src/play/play.html")
  if (existsSync(html)) {
    writeFileSync(html, readFileSync(html, "utf8")
      .replace(/data-map-width="\d+"/, `data-map-width="${source.width}"`)
      .replace(/data-map-height="\d+"/, `data-map-height="${source.height}"`)
      .replace(/(<div id="mapwrap" style=")[^"]*"/, `$1width: ${source.width}px; height: ${source.height}px"`))
  }
  console.log(`${source.kind} map: ${source.spaces.length} spaces, ${source.borders.length} borders`)
}
